func TestTrimSpace(t *testing.T) {
	tests := []struct {
		s string
		e string
	}{
		{"\u00A0hi\u00A0", "\u00A0hi\u00A0"},
		{"\u0085hello   ", "\u0085hello"},
	}
	for _, test := range tests {
		myString := TrimSpace(test.s)
		if myString != test.e {
			t.Errorf("[FAIL] Expected: \"%s\". Got: \"%s\". Input \"%s\".", test.e, myString, test.s)
		}
	}

	for _, str := range TestWords {
		myString := TrimSpace(str)
		stdString := strings.TrimSpace(str)
		if myString != stdString {
			t.Errorf("[FAIL] Expected: \"%s\". Got: \"%s\". Input \"%s\".", stdString, myString, str)
		}
	}
}

